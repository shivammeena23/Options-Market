import yfinance as yf
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

def MACD(df, short_window=12, long_window=26, signal_window=9):
    df['EMA12'] = df['Close'].ewm(span=short_window, adjust=False).mean()
    df['EMA26'] = df['Close'].ewm(span=long_window, adjust=False).mean()
    df['MACD'] = df['EMA12'] - df['EMA26']
    df['Signal Line'] = df['MACD'].ewm(span=signal_window, adjust=False).mean()
    return df

def generate_signals(df, short_window=12):
    df['Signal'] = 0
    df['Signal'][short_window:] = np.where(df['MACD'][short_window:] > df['Signal Line'][short_window:], 1, 0)
    df['Signal'] = np.where(df['MACD'] < df['Signal Line'], -1, df['Signal'])
    return df

def backtest_strategy(df, indicator):
    initial_balance = 10000
    balance = initial_balance
    shares = 0
    for i in range(1, len(df)):
        if indicator == 'MACD':
            if df['MACD'][i] > df['Signal Line'][i] and balance > 0:
                shares = balance // df['Close'][i]
                balance -= shares * df['Close'][i]
            elif df['MACD'][i] < df['Signal Line'][i] and shares > 0:
                balance += shares * df['Close'][i]
                shares = 0
        elif indicator == 'EMA':
            if df['Close'][i] > df['EMA'][i] and balance > 0:
                shares = balance // df['Close'][i]
                balance -= shares * df['Close'][i]
            elif df['Close'][i] < df['EMA'][i] and shares > 0:
                balance += shares * df['Close'][i]
                shares = 0
    return balance

def calculate_performance(portfolio_value):
    returns = pd.Series(portfolio_value).pct_change().dropna()
    sharpe_ratio = returns.mean() / returns.std() * np.sqrt(252)
    return returns, sharpe_ratio

sensex = yf.download('^BSESN', start='2021-01-01', end='2024-01-01')

sensex = MACD(sensex)
sensex = generate_signals(sensex)

portfolio_value, balance = backtest_strategy(sensex)
returns, sharpe_ratio = calculate_performance(portfolio_value)

# Output the results
print(f'Final portfolio value: INR {balance}')
print(f'Sharpe Ratio: {sharpe_ratio}')

plt.figure(figsize=(12, 6))
plt.plot(sensex.index, portfolio_value, label='Portfolio Value')
plt.title('Portfolio Value Over Time')
plt.xlabel('Date')
plt.ylabel('Portfolio Value (INR)')
plt.legend()
plt.show()