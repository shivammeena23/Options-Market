def butterfly_spread_profit_loss(K1, K2, K3, P1, P2, P3, S):


    net_premium_paid = P1 - 2 * P2 + P3   #calculate net premium paid

    if S <= K1:         #payoff at expiration
        payoff = 0
    elif K1 < S <= K2:
        payoff = S - K1
    elif K2 < S <= K3:
        payoff = (S - K1) - 2 * (S - K2)
    else:  # S > K3
        payoff = (S - K1) - 2 * (S - K2) + (S - K3)

    profit_loss = payoff - net_premium_paid

    return profit_loss

# Example usage:
K1 = 50  # strike price for 1st call option
K2 = 60  # strike price for 2nd call option
K3 = 65  # strike price for 3rd call option
P1 = 2.0  # premium paid for the 1st call option
P2 = 2.5  # premium received for each of the 2nd call options
P3 = 1.0  # premium paid for the 3rd option
S = 58  # Spot price

profit_loss = butterfly_spread_profit_loss(K1, K2, K3, P1, P2, P3, S)
print(f"Potential Profit/Loss: {profit_loss}")