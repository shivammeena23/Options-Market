import yfinance as yf
import math

def stockdata(ticker):
    stock=yf.Ticker(ticker)
    data=stock.history(period='1y',interval='1d')
    return data

def volatility(data):
    daily_change=[]
    prev=1
    for close_price in data['Close']:
        daily_return = (close_price - prev) / prev
        daily_change.append(daily_return)
        prev = close_price
    data['daily_change']=daily_change
    daily_volatility=data['daily_change'].std()
    annulaized_volatility= daily_volatility*(math.sqrt(252))
    return daily_volatility, annulaized_volatility

lst=['AAPL','GOOGL','MSFT','AMZN','META']
for ticker in lst:
    daily_v,annualized_v=volatility(stockdata(ticker))
    print(f"Daily volatitlity of {ticker} is {daily_v} and annualized volatility is {annualized_v}\n")

